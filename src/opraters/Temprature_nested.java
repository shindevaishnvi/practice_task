package opraters;

public class Temprature_nested {
	public static void main(String[] args) {
		int temp = 25;
		if (temp > 30) {
			System.out.println("Hot");
		} else if (temp > 20) {
			System.out.println("warm");
		} else if (temp > 10) {
			System.out.println("cool");
		} else {
			System.out.println("cold");
		}

	}

}
